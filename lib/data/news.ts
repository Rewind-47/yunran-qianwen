/** 按「置顶优先 + 日期倒序」排好的列表 */
export const newsSorted: NewsItem[] = [...news].sort((a, b) => {
  if (!!a.pinned !== !!b.pinned) return a.pinned ? -1 : 1;
  return a.date < b.date ? 1 : -1;
});

export function newsBySlug(slug: string): NewsItem | undefined {
  return news.find((n) => n.slug === slug);
}

/** 首页公告栏用：取最新的若干条 */
export function latestNews(count = 5): NewsItem[] {
  return newsSorted.slice(0, count);
}

/** 详情页底部：按时间顺序取上一篇 / 下一篇 */
export function newsNeighbors(slug: string) {
  const i = newsSorted.findIndex((n) => n.slug === slug);
  return {
    prev: i > 0 ? newsSorted[i - 1] : undefined,
    next: i >= 0 && i < newsSorted.length - 1 ? newsSorted[i + 1] : undefined,
  };
}

/** 2026-10-15 → 2026.10.15 */
export function longDate(iso: string) {
  return iso.replaceAll("-", ".");
}

/** 2026-10-15 → 10-15 */
export function shortDate(iso: string) {
  return iso.slice(5);
}

/** 2026-10-15 → 二〇二六年十月十五日（详情页抬头用） */
export function cnDate(iso: string) {
  const [y, m, d] = iso.split("-").map(Number);
  const digits = ["〇", "一", "二", "三", "四", "五", "六", "七", "八", "九"];
  const toCn = (n: number) => {
    if (n <= 10) return n === 10 ? "十" : digits[n];
    if (n < 20) return "十" + digits[n % 10];
    const t = Math.floor(n / 10);
    return digits[t] + "十" + (n % 10 ? digits[n % 10] : "");
  };
  const year = String(y)
    .split("")
    .map((c) => digits[Number(c)])
    .join("");
  return `${year}年${toCn(m)}月${toCn(d)}日`;
}
