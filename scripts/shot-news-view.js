const { chromium } = require("playwright-core");
const fs = require("fs");
const exe = ["C://Program Files (x86)//Microsoft//Edge//Application//msedge.exe","C://Program Files//Microsoft//Edge//Application//msedge.exe"].find(p=>fs.existsSync(p));
(async () => {
  const browser = await chromium.launch({ executablePath: exe, args: ["--use-gl=swiftshader","--disable-gpu-sandbox"] });
  const errors = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 940 }, deviceScaleFactor: 2 });
  page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
  page.on("pageerror", e => errors.push("pageerror: " + e.message));
  await page.goto("http://localhost:3000/", { waitUntil: "networkidle", timeout: 180000 });
  await page.waitForTimeout(1500);
  await page.evaluate(() => document.fonts.ready);
  const news = await page.locator("#news").boundingBox();
  await page.evaluate((y) => window.scrollTo(0, y), news.y - 60);
  await page.waitForTimeout(1200);
  await page.screenshot({ path: "outputs/news-view-1.png" });
  await page.evaluate((y) => window.scrollTo(0, y), news.y + 420);
  await page.waitForTimeout(1200);
  await page.screenshot({ path: "outputs/news-view-2.png" });

  const m = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await m.goto("http://localhost:3000/", { waitUntil: "networkidle", timeout: 180000 });
  await m.waitForTimeout(1500);
  const n2 = await m.locator("#news").boundingBox();
  await m.evaluate((y) => window.scrollTo(0, y), n2.y - 40);
  await m.waitForTimeout(1000);
  await m.screenshot({ path: "outputs/news-view-mobile.png" });
  console.log("errors:", JSON.stringify(errors.slice(0, 6)));
  await browser.close();
})();
